"""The operator resolver: exactly this model's operators, and nothing else.

The resolver decides which kernels exist on the device. One operator too few and inference fails at
initialisation; one too many and flash pays for a kernel nothing calls. So it is generated from the
operator set read out of the model file — never from a list a desktop runtime produced, which
contains a delegate node that exists only on a desktop (``runtime/flatbuffer.py``).

The method names come from a table and not from a rule. ``Add`` plus the camel-cased operator name
is the obvious implementation and it emits code that does not compile: the runtime spells it
``AddConv2D``, ``AddSvdf``, ``AddL2Pool2D``. And there is no escape hatch, because the generic
``AddBuiltin`` is private — so an operator with no public method of its own cannot be registered at
all, and that refuses the run rather than handing the author a compiler error.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any

from caravan.export.methods import CUSTOM_METHOD, READ_ON, SOURCE, method_for
from caravan.manifest.errors import RULE_OPERATOR_UNRESOLVABLE, run_rule_error

HEADER_NAME = "resolver.h"


def unresolvable(operators: Sequence[Any]) -> tuple[str, ...]:
    """The operators this runtime has no public method for. Custom operators are resolvable."""
    return tuple(
        operator.name
        for operator in operators
        if not operator.is_custom and method_for(operator.name) is None
    )


def generate(operators: Sequence[Any]) -> str:
    """The resolver header for a graph's operator set, in graph order.

    Graph order rather than alphabetical: a reader comparing this with the report or with a
    visualisation of the model should not have to re-sort one of them.
    """
    missing = unresolvable(operators)
    if missing:
        run_rule_error(
            RULE_OPERATOR_UNRESOLVABLE,
            "export.formats",
            (
                f"the model uses {', '.join(missing)}, which the runtime's resolver has no method "
                f"for; caravan reads its methods from {SOURCE} (read {READ_ON}), and generating a "
                "resolver without them would produce code that does not compile"
            ),
            found=list(missing),
        )

    count = len(operators)
    lines = []
    for operator in operators:
        nodes = f"{operator.nodes} node" + ("s" if operator.nodes != 1 else "")
        if operator.is_custom:
            lines.append(
                f'  resolver.{CUSTOM_METHOD}("{operator.custom_name}", /* your registration */'
                f" nullptr);  /* custom, {nodes} — you must supply the kernel */"
            )
        else:
            method = method_for(operator.name)
            lines.append(
                f"  resolver.{method}();  /* {operator.name} v{operator.version}, {nodes} */"
            )
    body = "\n".join(lines)
    return (
        f"/* {HEADER_NAME} — generated by caravan; do not edit.\n"
        f" * {count} distinct operator" + ("s" if count != 1 else "") + " in "
        f"{sum(operator.nodes for operator in operators)} nodes, read from the model file itself.\n"
        " * Method names from " + SOURCE + f" (read {READ_ON}).\n"
        " */\n"
        "#ifndef CARAVAN_RESOLVER_H_\n"
        "#define CARAVAN_RESOLVER_H_\n\n"
        '#include "tensorflow/lite/micro/micro_mutable_op_resolver.h"\n\n'
        f"inline tflite::MicroMutableOpResolver<{count}> CaravanResolver() {{\n"
        f"  tflite::MicroMutableOpResolver<{count}> resolver;\n"
        f"{body}\n"
        "  return resolver;\n"
        "}\n\n"
        "#endif  /* CARAVAN_RESOLVER_H_ */\n"
    )
