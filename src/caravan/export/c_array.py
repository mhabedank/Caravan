"""The model as C source, written the way the runtime's own generator writes it.

Copied in form rather than invented, from ``tensorflow/lite/micro/tools/generate_cc_arrays.py``
(read 2026-10-22), so that an author who has seen a model array before sees nothing new here:

    alignas(16) const unsigned char g_model_data[] = {0x1c, 0x00, ...};
    constexpr unsigned int g_model_data_size = 7856;

``alignas(16)`` is not stylistic. The runtime needs the model buffer aligned, and an unaligned one
fails at initialisation on the target — a long way from this machine, with nothing to point at.

The output is deterministic: the bytes, the name, the length, and nothing else. No timestamp, no
path, no host name, so the same model exports to identical files and a diff of two runs says
something.
"""

from __future__ import annotations

#: Bytes per line of the generated array. Wide enough that a 16 KB model is not 16,000 lines, and
#: narrow enough that a reviewer can still read one.
BYTES_PER_LINE = 12

#: What the runtime's own generator aligns a model buffer to.
ALIGNMENT = 16

SOURCE = "tensorflow/lite/micro/tools/generate_cc_arrays.py in tensorflow/tflite-micro"
READ_ON = "2026-10-22"


def array_name(stem: str) -> str:
    """``g_<stem>``, with anything that is not a C identifier character turned into ``_``.

    The runtime's generator derives ``g_<stem>_model_data`` from a file called ``<stem>.tflite``.
    Here the file is already called ``model_data``, so the suffix is in the stem and adding it again
    would give ``g_model_data_data``.
    """
    cleaned = "".join(character if character.isalnum() else "_" for character in stem)
    return f"g_{cleaned}"


def header(stem: str, length: int, additions: str = "") -> str:
    """The declaration and the length, for whatever includes the array.

    ``additions`` is the interface of feature 006 — which model, the named positions, the label
    array — placed inside the include guard. Empty, the header is exactly feature 004's.
    """
    name = array_name(stem)
    guard = f"{name.upper()}_H_"
    return (
        f"/* {stem}.h — generated by caravan; do not edit.\n"
        f" * The model as a byte array. Form follows {SOURCE}\n"
        f" * (read {READ_ON}), so a reader who has seen a model array before sees nothing new.\n"
        " */\n"
        f"#ifndef {guard}\n"
        f"#define {guard}\n\n"
        "#include <cstdint>\n\n"
        f"constexpr unsigned int {name}_size = {length};\n"
        f"extern const unsigned char {name}[];\n\n"
        + (f"{additions}\n" if additions else "")
        + f"#endif  /* {guard} */\n"
    )


def source(stem: str, blob: bytes, additions: str = "") -> str:
    """The array itself, aligned as the runtime requires, and then ``additions`` (feature 006)."""
    name = array_name(stem)
    lines = []
    for start in range(0, len(blob), BYTES_PER_LINE):
        chunk = blob[start : start + BYTES_PER_LINE]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    body = "\n".join(lines)
    return (
        f"/* {stem}.cc — generated by caravan; do not edit.\n"
        f" * {len(blob)} bytes. alignas({ALIGNMENT}) is required, not stylistic: the runtime\n"
        " * needs the model buffer aligned, and an unaligned one fails at initialisation on\n"
        " * the target.\n"
        " */\n"
        f'#include "{stem}.h"\n\n'
        "#include <cstdint>\n\n"
        f"alignas({ALIGNMENT}) const unsigned char {name}[] = {{\n"
        f"{body}\n"
        "};\n" + (f"\n{additions}" if additions else "")
    )


def read_back(generated: str) -> bytes:
    """The bytes a generated source declares, parsed back out of it.

    Here rather than in a test because the round-trip is a promise of this module, and a promise
    checked by code that lives beside it cannot drift from the code that makes it.
    """
    start = generated.index("= {") + 3
    # Up to the array's own closing brace: since feature 006 the label array follows it.
    body = generated[start : generated.index("};", start)]
    return bytes(
        int(token, 16) for token in body.replace("\n", "").replace(" ", "").split(",") if token
    )
