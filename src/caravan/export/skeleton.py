"""The runner skeleton: what a firmware author starts from, and what they still owe.

Emitted and never compiled. Nothing in this project cross-compiles it — no ARM or Xtensa toolchain
is installed and the runtime is not vendored — so nothing here claims it builds. Saying otherwise
would be exactly the unverified claim Principle IV exists against, and the stage that *can* make
that claim is emulated verification.

What the skeleton is for is the handover: the runtime the board declares, the two generated
headers, the working-memory constant with the floor and the warning that the floor is not the
figure, and the three places where the author's own code goes.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any

#: A starting value for the arena, as a multiple of the floor. Not a prediction — a number that
#: lets the author compile before they have measured anything, with a comment telling them it is
#: not the answer. Four, because the floor omits scratch buffers and bookkeeping of unknown size,
#: and a value that fails to initialise teaches nothing about how far off it was.
FLOOR_HEADROOM = 4

#: Rounded up to this, because arenas are configured in round numbers and a constant like 2,592
#: invites the reader to believe somebody computed it.
ARENA_GRANULARITY = 1024


def _elements(shape: tuple[int, ...]) -> int:
    """How many values a tensor of this shape holds — what the runner's loops count in."""
    count = 1
    for dim in shape:
        count *= dim
    return count


def arena_start(floor_bytes: int) -> int:
    """A compilable starting value: the floor with headroom, rounded up."""
    wanted = max(floor_bytes * FLOOR_HEADROOM, ARENA_GRANULARITY)
    return -(-wanted // ARENA_GRANULARITY) * ARENA_GRANULARITY


#: The C element type and the tensor's data member, per element type of the model's boundary.
_C_TYPES = {
    "float32": ("float", "f"),
    "int32": ("int32_t", "i32"),
    "int8": ("int8_t", "int8"),
}


def generate(
    *,
    board: Any,
    graph: Any,
    model_stem: str,
    array_name: str,
    accelerated: int,
    operators_total: int,
    inputs: Sequence[Mapping[str, Any]],
    output: Mapping[str, Any],
) -> str:
    """The skeleton for one target board.

    ``inputs`` and ``output`` are the bindings read from the model file. The runner binds each by
    the named position the header declares (feature 006), never by a literal index, and fills each
    input with raw values (feature 008): no scale, zero point, mean or vocabulary appears here,
    because the model applies them itself (SC-005).
    """
    accel = board.accel or "none declared"
    arena = arena_start(graph.working_memory_floor)
    clock = f"{board.clock_mhz:g}"
    out_type, out_member = _C_TYPES[output["element_type"]]
    out_count = _elements(tuple(output["shape"]))

    declarations: list[str] = []
    fills: list[str] = []
    describe: list[str] = []
    for binding in inputs:
        c_type, member = _C_TYPES[binding["element_type"]]
        name = binding["name"]
        count = _elements(tuple(binding["shape"]))
        function = f"Fill_{name}"
        declarations.append(f"static void {function}({c_type}* values, int count);")
        fills.append(
            f"    {function}(interpreter.input({array_name}_input_{name})->data.{member}, {count});"
        )
        describe.append(f" *   {name}: {count} x {c_type}")
    nl = "\n"
    return f"""/* main.cc — skeleton generated by caravan; edit freely, this file is yours.
 *
 * Board:            {board.board} ({board.core}, {clock} MHz)
 * Runtime:          {board.toolchain.runtime}, as this board's description declares
 * Accelerated with: {accel} — {accelerated} of {operators_total} operators covered
 * Compiler:         {board.toolchain.compiler} {board.toolchain.optimization}
 *
 * Caravan has NOT compiled, linked or run this file. It emits it and states what the model needs;
 * building it is yours, and verifying the build is what caravan's emulated verification stage does.
 *
 * You supply three things: the runtime's sources on your include path, the readings of each input
 * in its Fill_ function, and whatever you do with the answer in UseOutput.
 */
#include "{model_stem}.h"
#include "resolver.h"
#include "tensorflow/lite/micro/micro_interpreter.h"
#include "tensorflow/lite/micro/micro_mutable_op_resolver.h"

/* Working memory for the interpreter.
 *
 * The floor is {graph.working_memory_floor} bytes: the peak of simultaneously live tensors,
 * computed from the model file. It is a floor and NOT the figure this board needs — the runtime
 * also needs scratch buffers and its own bookkeeping, and it plans the whole arena with its own
 * allocator, here, at run time. The value below is the floor with headroom so that you can
 * compile today. If initialisation fails, raise it; to know what it really is, measure it.
 */
constexpr int kArenaBytes = {arena};
alignas(16) static uint8_t g_arena[kArenaBytes];

/* Every input takes raw values, as your sensors give them, one window at a time; the model
 * prepares them itself. model_data.h says what each one is:
{nl.join(describe)}
 * The output gives {out_count} x {out_type}. */
{nl.join(declarations)}
static void UseOutput(const {out_type}* output, int count);

int main() {{
  const tflite::Model* model = tflite::GetModel({array_name});
  tflite::MicroMutableOpResolver<{len(graph.operators)}> resolver = CaravanResolver();
  tflite::MicroInterpreter interpreter(model, resolver, g_arena, kArenaBytes);

  if (interpreter.AllocateTensors() != kTfLiteOk) {{
    /* The commonest cause is kArenaBytes being too small. See the note above it. */
    return 1;
  }}

  TfLiteTensor* output = interpreter.output({array_name}_output_{output["name"]});
  for (;;) {{
{nl.join(fills)}
    if (interpreter.Invoke() != kTfLiteOk) {{
      return 2;
    }}
    UseOutput(output->data.{out_member}, {out_count});
  }}
}}
"""
